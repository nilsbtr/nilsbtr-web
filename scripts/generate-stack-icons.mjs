/**
 * Turns the hand-drawn SVGs in src/features/stack/icons into icon data that
 * <HugeiconsIcon> renders like any icon from @hugeicons/core-free-icons.
 *
 * The SVGs follow the Hugeicons conventions: a 24×24 viewBox, no fill and a
 * 1.5 round stroke in currentColor. Run `pnpm icons:generate` after adding or
 * editing one.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const ICONS_DIR = new URL("../src/features/stack/icons/", import.meta.url);
const OUTPUT = new URL("index.ts", ICONS_DIR);

const ELEMENT = /<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/>/g;
const ATTRIBUTE = /([\w-]+)="([^"]*)"/g;

const camelCase = (name) => name.replace(/-(\w)/g, (_, char) => char.toUpperCase());
const pascalCase = (name) => camelCase(`-${name}`);

function parse(file) {
  const svg = readFileSync(new URL(file, ICONS_DIR), "utf8");
  if (!svg.includes('viewBox="0 0 24 24"')) {
    throw new Error(`${file}: icons must use a 24×24 viewBox`);
  }

  const elements = [...svg.matchAll(ELEMENT)].map(([, tag, attributes], index) => {
    const props = Object.fromEntries(
      [...attributes.matchAll(ATTRIBUTE)].map(([, name, value]) => [camelCase(name), value])
    );
    return [tag, { ...props, key: String(index) }];
  });
  if (elements.length === 0) throw new Error(`${file}: no drawable elements found`);

  return elements;
}

const files = readdirSync(ICONS_DIR)
  .filter((file) => file.endsWith(".svg"))
  .sort();

const exports = files.map((file) => {
  const name = `${pascalCase(file.replace(/\.svg$/, ""))}Icon`;
  return `export const ${name}: IconSvgElement = ${JSON.stringify(parse(file))};`;
});

writeFileSync(
  OUTPUT,
  [
    "// Generated by scripts/generate-stack-icons.mjs from the SVGs in this folder. Do not edit.",
    'import type { IconSvgElement } from "@hugeicons/react";',
    ...exports,
    "",
  ].join("\n\n")
);

console.log(`Generated ${files.length} icons.`);
